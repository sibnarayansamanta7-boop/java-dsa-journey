public class Wrapper {
    public static void main(String[] args) {


        //this wrapper class don't do anything
        // Just define the object in object
        // Autoboxing
        int a = 123;
        Double b = 2.9;
        Character c = '$';
        Boolean d = true;

        // Unboxing

        Integer x = a;

        System.out.println(x);
    }
}
